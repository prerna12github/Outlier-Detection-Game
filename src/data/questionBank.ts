/**
 * Filter questions based on mode and difficulty, or fallback if specific difficulty is scarce
 */
export function getQuestionsForGame(mode: Question['mode'], difficulty: Question['difficulty'], count = 5): Question[] {
  let matched = QUESTION_BANK.filter((q) => q.mode === mode && q.difficulty === difficulty);

  // If not enough for the exact difficulty in that mode, widen to the mode
  if (matched.length < count) {
    const modePool = QUESTION_BANK.filter((q) => q.mode === mode);
    matched = modePool;
  }

  // Shuffle questions randomly
  const shuffled = [...matched].sort(() => Math.random() - 0.5);
  return shuffled.slice(0, count);
}
